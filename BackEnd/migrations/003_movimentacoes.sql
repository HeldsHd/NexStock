BEGIN;

CREATE TABLE IF NOT EXISTS movimentacoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id INTEGER REFERENCES produtos(id) ON DELETE SET NULL,
  produto_nome TEXT NOT NULL,
  produto_codigo TEXT NOT NULL,
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  estoque_anterior INTEGER NOT NULL CHECK (estoque_anterior >= 0),
  estoque_novo INTEGER NOT NULL CHECK (estoque_novo >= 0),
  usuario_nome TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS movimentacoes_created_at_id_idx
  ON movimentacoes (created_at DESC, id DESC);

COMMIT;
